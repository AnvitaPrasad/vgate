#!/usr/bin/env bash
# Package src/vgate as the private Kaggle dataset `<user>/vgate-code`, mounted by every GPU job.
# A content-hash build stamp is written to src/vgate/_build.py; jobs assert it (catches stale mounts).
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
KUSER="$(cat "$ROOT/.kaggle-cfg/username")"
STAGE="$ROOT/kaggle/_dataset_vgate-code"
rm -rf "$STAGE" && mkdir -p "$STAGE"
python3 - <<'PY'
import hashlib, pathlib
src = pathlib.Path("src/vgate")
files = sorted(p for p in src.rglob("*") if p.is_file() and p.name != "_build.py" and "__pycache__" not in p.parts
               and p.suffix in (".py", ".npz"))  # code and the frozen gate arrays (src/vgate/gates)
stamp = hashlib.sha256(b"".join(p.read_bytes() for p in files)).hexdigest()[:12]
(src / "_build.py").write_text('"""Auto-generated by scripts/sync_kaggle_dataset.sh."""\nBUILD = "' + stamp + '"\n')
print("build stamp", stamp)
PY
cp -r "$ROOT/src/vgate" "$STAGE/vgate"
find "$STAGE" -name __pycache__ -exec rm -rf {} +
cat > "$STAGE/dataset-metadata.json" <<META
{"title": "vgate-code", "id": "$KUSER/vgate-code", "licenses": [{"name": "CC0-1.0"}]}
META
if "$ROOT/scripts/kaggle.sh" datasets status "$KUSER/vgate-code" >/dev/null 2>&1; then
  "$ROOT/scripts/kaggle.sh" datasets version -p "$STAGE" -r zip -m "${1:-sync $(date -u +%FT%TZ)}"
else
  "$ROOT/scripts/kaggle.sh" datasets create -p "$STAGE" -r zip
fi
