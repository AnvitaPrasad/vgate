"""Live VGate: one image + one question -> closed-book answer, search decision, retrieval, read decision, answer.

  closed-book pass (hidden state + token statistics)          -> a_0, VGate-pre  u_pre  = P(help) - P(harm)
  if u_pre > 0:  caption pass, dense retrieval (bge)          -> top-20 scores, VGate-full u_full
  if u_full > 0: evidence pass over the top-5 passages        -> a_E
The gates are the mixed-traffic gates of the paper (fit on the pooled development sets), frozen to plain arrays by
scripts/freeze_gates.py so that no scikit-learn pickle is needed. The retriever is the OK-VQA one
(BAAI/bge-base-en-v1.5 over the M2KR Wikipedia passages, query = caption + question); the caption is generated by
the VLM because a visitor's image has none. Every executed pass is charged to the cost ledger in the result.
"""
import json
import pathlib
import time

import numpy as np

from . import prompts
from . import uncertainty as U

GATES_DIR = pathlib.Path(__file__).parent / "gates"
CAPTION = "Describe this image in one short sentence."
BGE_QUERY = "Represent this sentence for searching relevant passages: "
RETRIEVER = "BAAI/bge-base-en-v1.5"


class Gates:
    """VGate-pre and VGate-full as arrays: standardise -> PCA-64 (hidden state) -> standardise -> multinomial logit."""

    def __init__(self, path):
        z = np.load(path, allow_pickle=False)
        self.z = {k: z[k] for k in z.files}
        self.base = [str(x) for x in self.z["base_names"]]
        self.layer = int(self.z["layer"])

    def _pcs(self, h):
        x = (np.asarray(h, dtype=np.float64) - self.z["h_mean"]) / self.z["h_scale"]
        return (x - self.z["pca_mean"]) @ self.z["pca_components"].T

    def _benefit(self, x, name):
        z = self.z
        x = (x - z[f"{name}_mean"]) / z[f"{name}_scale"]
        logit = x @ z[f"{name}_coef"].T + z[f"{name}_intercept"]
        p = np.exp(logit - logit.max(-1, keepdims=True))
        p /= p.sum(-1, keepdims=True)
        cls = list(z[f"{name}_classes"])
        return p[..., cls.index(1)] - p[..., cls.index(-1)]

    def pre(self, h):
        return self._benefit(self._pcs(h), "pre")

    def full(self, feats, h):
        """feats: array [..., len(base)] in the order of `self.base` (NaN -> 0, as in training)."""
        return self._benefit(np.concatenate([np.nan_to_num(np.asarray(feats, dtype=np.float64)), self._pcs(h)], -1), "full")


class Retriever:
    """Exact dense retrieval over a saved passage matrix (rows L2-normalised bge embeddings)."""

    def __init__(self, index_dir, device="cpu"):
        from sentence_transformers import SentenceTransformer
        index_dir = pathlib.Path(index_dir)
        self.P = np.load(index_dir / "passage_emb.npy").astype(np.float32)
        self.meta = [json.loads(l) for l in open(index_dir / "passages.jsonl")]
        assert len(self.meta) == len(self.P)
        self.enc = SentenceTransformer(RETRIEVER, device=device)
        self.enc.max_seq_length = 256

    def search(self, query, k=20):
        q = self.enc.encode([BGE_QUERY + query], normalize_embeddings=True, convert_to_numpy=True).astype(np.float32)[0]
        s = self.P @ q
        top = np.argpartition(-s, k)[:k]
        top = top[np.argsort(-s[top])]
        return [dict(id=self.meta[i]["id"], title=self.meta[i]["title"], text=self.meta[i]["text"], score=float(s[i])) for i in top]


class LivePipeline:
    def __init__(self, vlm, gates, retriever):
        self.vlm, self.gates, self.retriever = vlm, gates, retriever

    def answer(self, image, question, run_all=False):
        """run_all=True executes every pass regardless of the gates (for evaluation); the decisions and the cost VGate
        would have paid are reported either way."""
        rec, L, out, t = dict(question=question), self.gates.layer, dict(question=question), {}
        t0 = time.time()
        ne, hid = self.vlm.generate([image], [prompts.build("ne", rec)], hidden_layers=[L])
        t["closed_book"] = time.time() - t0
        ne, h = ne[0], hid[L][0].numpy()
        free = U.free_features(ne)
        u_pre = float(self.gates.pre(h))
        out.update(a0=ne["text"], u_pre=u_pre, search=bool(u_pre > 0), tok_closed_book=ne["n_prompt"] + ne["n_gen"],
                   read=False, final=ne["text"], hidden=h.astype(np.float16))
        if run_all or out["search"]:
            t0 = time.time()
            cap = self.vlm.generate([image], [CAPTION], max_new_tokens=40, want_logits=False)[0][0]
            t["caption"] = time.time() - t0
            t0 = time.time()
            hits = self.retriever.search(f"{cap['text']} {question}".strip())
            t["retrieval"] = time.time() - t0
            feats = {**free, **U.qpp([x["score"] for x in hits])}
            u_full = float(self.gates.full([feats[k] for k in self.gates.base], h))
            out.update(caption=cap["text"], tok_caption=cap["n_prompt"] + cap["n_gen"], evidence=hits[:5],
                       retr_scores=[x["score"] for x in hits], retr_ids=[x["id"] for x in hits], u_full=u_full,
                       read=bool(out["search"] and u_full > 0))
            if run_all or out["read"]:
                t0 = time.time()
                ev = self.vlm.generate([image], [prompts.build("ev", dict(rec, evidence=hits[:5]))])[0][0]
                t["evidence"] = time.time() - t0
                out.update(aE=ev["text"], tok_evidence=ev["n_prompt"] + ev["n_gen"])
                if out["read"]:
                    out["final"] = ev["text"]
        # what VGate pays: the closed-book pass, the caption pass if it searches, the evidence pass if it reads
        out["tok_vgate"] = (out["tok_closed_book"] + (out.get("tok_caption", 0) if out["search"] else 0)
                            + (out.get("tok_evidence", 0) if out["read"] else 0))
        out["seconds"] = {k: round(v, 3) for k, v in t.items()}
        return out
